    private void addMedicine(){
        String medicine = txtMed.getText().trim();
        String dosage = txtDosage.getText().trim();
        String frequency = txtFreq.getText().trim();
        String duration = txtDuration.getText().trim();
        String quantity = txtQuan.getText().trim();
        String instructions = txtInstructions.getText().trim();
        
        if(medicine.isEmpty()||dosage.isEmpty()
                ||frequency.isEmpty()||duration.isEmpty()
                ||quantity.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please enter the medicine, dosage, frequency, duration and quantity."
            , "Missing Information", JOptionPane.WARNING_MESSAGE);
            return;
        }
        DefaultTableModel model = (DefaultTableModel)tblPrescriptions.getModel();
        model.addRow(new Object[]{
            medicine,
            dosage, 
            frequency,
            duration,
            quantity,
            instructions
        });
        txtMed.setText("");
        txtDosage.setText("");
        txtFreq.setText("");
        txtDuration.setText("");
        txtQuan.setText("");
        txtInstructions.setText("");
        
        txtMed.requestFocus();
    }
    private void removeMedicine(){
        int selectedRow = tblPrescriptions.getSelectedRow();
        
        if(selectedRow == -1){
            JOptionPane.showMessageDialog(this, "Please selecte a medicine from the table first.", "No Medicine Selected.", JOptionPane.WARNING_MESSAGE);
            return;
        }
        DefaultTableModel model = (DefaultTableModel)tblPrescriptions.getModel();
        model.removeRow(selectedRow);
    }
   private void savePrescription() {

    if (patientID == 0 || staffID == 0) {
        JOptionPane.showMessageDialog(
                this,
                "Patient or staff information is missing.",
                "Prescription Error",
                JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    DefaultTableModel model =
            (DefaultTableModel) tblPrescriptions.getModel();

    if (model.getRowCount() == 0) {
        JOptionPane.showMessageDialog(
                this,
                "Please add at least one medicine.",
                "No Medicines",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String sql = "INSERT INTO Prescriptions "
            + "(PatientID, DoctorID, PrescriptionDate, Medicine, "
            + "Dosage, Frequency, Duration, Quantity, Instructions, Status) "
            + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'PENDING')";

    try {
        Connection conn = DBConnection.getConnection();
        PreparedStatement pst = conn.prepareStatement(sql);

        for (int i = 0; i < model.getRowCount(); i++) {

            Object medicineObj = model.getValueAt(i, 0);
            Object dosageObj = model.getValueAt(i, 1);
            Object frequencyObj = model.getValueAt(i, 2);
            Object durationObj = model.getValueAt(i, 3);
            Object quantityObj = model.getValueAt(i, 4);
            Object instructionsObj = model.getValueAt(i, 5);

            // Make sure no required table value is null
            if (medicineObj == null
                    || dosageObj == null
                    || frequencyObj == null
                    || durationObj == null
                    || quantityObj == null) {

                JOptionPane.showMessageDialog(
                        this,
                        "One or more medicine details are missing.\n"
                        + "Please check the prescription table.",
                        "Incomplete Prescription",
                        JOptionPane.WARNING_MESSAGE
                );

                pst.close();
                conn.close();
                return;
            }

            pst.setInt(1, patientID);
            pst.setInt(2, staffID);
            pst.setString(3, java.time.LocalDate.now().toString());

            pst.setString(4, medicineObj.toString());
            pst.setString(5, dosageObj.toString());
            pst.setString(6, frequencyObj.toString());
            pst.setString(7, durationObj.toString());
            pst.setString(8, quantityObj.toString());

            if (instructionsObj == null) {
                pst.setString(9, "");
            } else {
                pst.setString(9, instructionsObj.toString());
            }

            pst.addBatch();
        }

        pst.executeBatch();

        pst.close();
        conn.close();

        JOptionPane.showMessageDialog(
                this,
                "Prescription saved successfully.",
                "Prescription Saved",
                JOptionPane.INFORMATION_MESSAGE
        );

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error saving prescription: " + e.getMessage(),
                "Prescription Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}
