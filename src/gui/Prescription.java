private void completeConsultation() {

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Complete this consultation?",
            "Complete Consultation",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    String sql =
            "UPDATE DoctorReferrals "
            + "SET Status = 'COMPLETED' "
            + "WHERE PatientID = ? "
            + "AND DoctorID = ? "
            + "AND UPPER(TRIM(Status)) = 'IN CONSULTATION'";

    try {

        Connection conn = DBConnection.getConnection();
        PreparedStatement pst = conn.prepareStatement(sql);

        pst.setInt(1, patientID);
        pst.setInt(2, staffID);

        int updated = pst.executeUpdate();

        pst.close();
        conn.close();

        if (updated > 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Consultation completed successfully.",
                    "Success",
                    JOptionPane.INFORMATION_MESSAGE
            );

            dispose();

            DoctorDashboard doctor = new DoctorDashboard();
            doctor.setLocationRelativeTo(null);
            doctor.setVisible(true);

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "No active referral was found for this patient "
                    + "and doctor.",
                    "Referral Error",
                    JOptionPane.WARNING_MESSAGE
            );
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error completing consultation: " + e.getMessage(),
                "Completion Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}


