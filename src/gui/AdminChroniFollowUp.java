 private void loadFollowUps() {

    DefaultTableModel model = (DefaultTableModel) tblFollowUps.getModel();
    model.setRowCount(0);

    String sql =
        "SELECT cf.FollowUpID, " +
        "       p.PatientID, " +
        "       p.FullName, " +
        "       cf.CreatedDate, " +
        "       cf.ExpectedVisitDate, " +
        "       cf.LastVisitDate, " +
        "       cf.AssignedCHWID, " +
        "       cf.Status, " +
        "       cf.Escalated " +
        "FROM ChronicFollowUp cf " +
        "JOIN Patients p ON cf.PatientID = p.PatientID " +
        "WHERE cf.Status IN " +
        "('UNASSIGNED', 'IN PROGRESS', 'COMPLETE', 'ESCALATED') " +
        "ORDER BY p.PatientID ASC";
try (Connection con = DBConnection.getConnection();
     PreparedStatement pst = con.prepareStatement(sql);
     ResultSet rs = pst.executeQuery()) {

    int number = 1;

    while (rs.next()) {

            int patientID = rs.getInt("PatientID");
            String patientName = rs.getString("FullName");
            String createdDate = rs.getString("CreatedDate");
            String expectedDate = rs.getString("ExpectedVisitDate");
            String lastVisitDate = rs.getString("LastVisitDate");

            int chwID = rs.getInt("AssignedCHWID");
            boolean chwExists = !rs.wasNull();

            String status = rs.getString("Status");
            int escalated = rs.getInt("Escalated");

            String chwName = "Unassigned";

            if (chwExists) {
                chwName = getCHWName(chwID);
            }

            long daysMissed = calculateDaysMissed(expectedDate);

            String escalationStatus =
                    escalated == 1 ? "YES" : "NO";
model.addRow(new Object[]{
    number++,
    String.format("%03d", patientID),
    patientName,
    createdDate,
    expectedDate,
    lastVisitDate,
    daysMissed + " days",
    chwName,
    status,
    escalationStatus
});
        }

    } catch (SQLException e) {

        e.printStackTrace();

        JOptionPane.showMessageDialog(
            this,
            "Error loading chronic follow-ups:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}
 private String getCHWName(int chwID) {

    String sql =
        "SELECT FullName " +
        "FROM Staff " +
        "WHERE StaffID = ?";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, chwID);

        try (ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                return rs.getString("FullName");
            }
        }

    } catch (SQLException e) {
        e.printStackTrace();
    }

    return "Unknown";
}
 private long calculateDaysMissed(String expectedDate) {

    try {

        LocalDate expected = LocalDate.parse(expectedDate);
        LocalDate today = LocalDate.now();

        return ChronoUnit.DAYS.between(expected, today);

    } catch (Exception e) {
        return 0;
    }
}
 private void assignCHW() {

    int selectedRow = tblFollowUps.getSelectedRow();

    if (selectedRow == -1) {

        JOptionPane.showMessageDialog(
            this,
            "Please select a chronic follow-up patient first.",
            "No Patient Selected",
            JOptionPane.WARNING_MESSAGE
        );

        return;
    }

int patientID = Integer.parseInt(
    tblFollowUps.getValueAt(selectedRow, 1).toString()
);
    int followUpID = getFollowUpID(patientID);

    if (followUpID == -1) {
        JOptionPane.showMessageDialog(
            this,
            "Could not find the follow-up case.",
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    String[] chwNames = loadActiveCHWs();

    if (chwNames.length == 0) {

        JOptionPane.showMessageDialog(
            this,
            "There are currently no active CHWs available.",
            "No CHWs Available",
            JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    String selectedCHW = (String) JOptionPane.showInputDialog(
        this,
        "Select a CHW to assign:",
        "Assign CHW",
        JOptionPane.PLAIN_MESSAGE,
        null,
        chwNames,
        chwNames[0]
    );

    if (selectedCHW == null) {
        return;
    }

    int chwID = getCHWID(selectedCHW);

    if (chwID == -1) {
        JOptionPane.showMessageDialog(
            this,
            "Could not find the selected CHW.",
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    String sql =
        "UPDATE ChronicFollowUp " +
        "SET AssignedCHWID = ?, " +
        "    Status = 'IN PROGRESS' " +
        "WHERE FollowUpID = ?";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, chwID);
        pst.setInt(2, followUpID);

        int updated = pst.executeUpdate();

        if (updated > 0) {
            AuditLogger.log("Assined CHW", "CHW " + chwID
            + " assigned to patient " + patientID);

            JOptionPane.showMessageDialog(
                this,
                "CHW successfully assigned.",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
            );

            loadFollowUps();
        }

    } catch (SQLException e) {
        e.printStackTrace();

        JOptionPane.showMessageDialog(
            this,
            "Error assigning CHW:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}
 private String[] loadActiveCHWs() {

    java.util.ArrayList<String> chwList =
        new java.util.ArrayList<>();

    String sql =
        "SELECT FullName " +
        "FROM Staff " +
        "WHERE Role = 'CHW' " +
        "AND Status = 'Active' " +
        "ORDER BY FullName";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {
            chwList.add(rs.getString("FullName"));
        }

    } catch (SQLException e) {
        e.printStackTrace();
    }

    return chwList.toArray(new String[0]);
}
