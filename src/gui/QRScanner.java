 private void addDoctorFollowUpToQueue(int patientID, String department) {

    String checkSQL =
            "SELECT ReferralID "
            + "FROM DoctorReferrals "
            + "WHERE PatientID = ? "
            + "AND QueueDate = date('now', 'localtime') "
            + "AND VisitType = 'Doctor Follow-up' "
            + "AND Status IN ('PENDING', 'IN CONSULTATION') "
            + "LIMIT 1";

    String queueNumberSQL =
            "SELECT COUNT(*) AS Total "
            + "FROM DoctorReferrals "
            + "WHERE ToDepartment = ? "
            + "AND QueueDate = date('now', 'localtime')";

    String insertSQL =
            "INSERT INTO DoctorReferrals "
            + "(PatientID, NurseID, DoctorID, ReferralDate, Reason, "
            + "Status, Notes, ToDepartment, QueueNumber, QueueDate, "
            + "CheckInTime, VisitType) "
            + "VALUES (?, NULL, NULL, date('now', 'localtime'), ?, "
            + "'PENDING', NULL, ?, ?, date('now', 'localtime'), "
            + "time('now', 'localtime'), 'Doctor Follow-up')";

    try {

        Connection conn = DBConnection.getConnection();

        // -----------------------------------------------------
        // Prevent duplicate doctor queue entry
        // -----------------------------------------------------
        PreparedStatement checkPst =
                conn.prepareStatement(checkSQL);

        checkPst.setInt(1, patientID);

        ResultSet checkRs =
                checkPst.executeQuery();

        if (checkRs.next()) {

            JOptionPane.showMessageDialog(
                    this,
                    "This patient is already in the doctor queue today.",
                    "Already Checked In",
                    JOptionPane.WARNING_MESSAGE
            );

            checkRs.close();
            checkPst.close();
            conn.close();

            return;
        }

        checkRs.close();
        checkPst.close();

        // -----------------------------------------------------
        // Get next doctor queue number
        // -----------------------------------------------------
        PreparedStatement queuePst =
                conn.prepareStatement(queueNumberSQL);

        queuePst.setString(1, department);

        ResultSet queueRs =
                queuePst.executeQuery();

        int total = 0;

        if (queueRs.next()) {
            total = queueRs.getInt("Total");
        }

        queueRs.close();
        queuePst.close();

        int nextNumber = total + 1;

        String prefix = getDepartmentPrefix(department);

        String queueNumber =
                prefix + "-D" + String.format("%03d", nextNumber);

        // -----------------------------------------------------
        // Insert doctor follow-up into DoctorReferrals
        // -----------------------------------------------------
        PreparedStatement insertPst =
                conn.prepareStatement(insertSQL);

        insertPst.setInt(1, patientID);
        insertPst.setString(
                2,
                "Doctor follow-up appointment"
        );
        insertPst.setString(3, department);
        insertPst.setString(4, queueNumber);

        int inserted =
                insertPst.executeUpdate();

        insertPst.close();
        conn.close();

        if (inserted > 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Patient checked in successfully.\n\n"
                    + "Doctor Queue Number: " + queueNumber + "\n"
                    + "Department: " + department + "\n"
                    + "Visit Type: Doctor Follow-up",
                    "Doctor Queue",
                    JOptionPane.INFORMATION_MESSAGE
            );
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error adding patient to doctor queue:\n"
                + e.getMessage(),
                "Doctor Queue Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

