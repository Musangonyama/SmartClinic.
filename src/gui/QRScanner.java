  private String getDepartmentPrefix(String department) {

    if (department == null) {
        return "GEN";
    }

    switch (department.trim().toLowerCase()) {

        case "general consultation":
            return "GC";

        case "martenal health":
        case "maternal health":
            return "MH";

        case "child health":
            return "CH";

        case "chronic care":
            return "CC";

        case "tb/respiratory":
            return "TB";

        case "mental health":
            return "MHT";

        case "family planning":
            return "FP";

        case "dental":
            return "DEN";

        default:
            return "GEN";
    }
}
