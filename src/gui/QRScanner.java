            + "Status, AppointmentType, Department "
            + "FROM Appointments "
            + "WHERE PatientID = ? "
            + "AND AppointmentDate > date('now', 'localtime') "
            + "AND Status NOT IN ('NO-SHOW', 'No-Show', 'CANCELED', 'CANCELLED') "
            + "ORDER BY AppointmentDate, AppointmentTime "
            + "LIMIT 1";

