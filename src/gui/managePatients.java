private void loadPatients() {

    DefaultTableModel model =
            (DefaultTableModel) tblPatients.getModel();

    model.setRowCount(0);

    String status = showingArchived ? "Archived" : "Active";

    String sql = "SELECT PatientID, FullName, NationalID, Phone, Status "
            + "FROM Patients "
            + "WHERE Status = ? "
            + "ORDER BY PatientID";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setString(1, status);

        try (ResultSet rs = pst.executeQuery()) {

            int number = 1;

            while (rs.next()) {

                String patientID = String.format(
                        "%03d", rs.getInt("PatientID")
                );

                model.addRow(new Object[]{
                    number,
                    patientID,
                    rs.getString("FullName"),
                    rs.getString("NationalID"),
                    rs.getString("Phone"),
                    rs.getString("Status")
                });

                number++;
            }
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error loading patients: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}



private int getSelectedPatientID() {

    int selectedRow = tblPatients.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a patient first."
        );
        return -1;
    }

    return Integer.parseInt(
            tblPatients.getValueAt(selectedRow, 1).toString()
    );
}

   
private void viewPatient() {

    int patientID = getSelectedPatientID();

    if (patientID == -1) {
        return;
    }

    drMedicalRecord record =
            new drMedicalRecord(patientID, "Admin", -1);

    record.setVisible(true);
    record.setLocationRelativeTo(null);

    dispose();
}

    private void archivePatient(){
        int selectedRow = tblPatients.getSelectedRow();
        if(selectedRow == -1){
            JOptionPane.showMessageDialog(this, "Please select a patient to archive");
            return;
        }
int patientID = Integer.parseInt(
        tblPatients.getValueAt(selectedRow, 1).toString()
);        String patientName = tblPatients.getValueAt(selectedRow, 2).toString();
       int confirmation = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to archive\n"
                + patientName
                + "?\n\nThe patient's records will not be deleted.",
        "Archive Patient",
        JOptionPane.YES_NO_OPTION,
        JOptionPane.WARNING_MESSAGE
);
        if(confirmation != JOptionPane.YES_OPTION){
            return;
        }
        String sql = "UPDATE Patients "
                + "SET Status = 'Archived' "
                + "WHERE PatientID = ?";
        try{
            Connection conn = DBConnection.getConnection();
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setInt(1, patientID);
            int rowsUpdated = pst.executeUpdate();
            if(rowsUpdated > 0){
                AuditLogger.log("Patient archived", "Patient " + patientName + "archived");
                JOptionPane.showMessageDialog(this, "Patient archived successfully.");
                loadPatients();
            }
        }catch(SQLException e){
            JOptionPane.showMessageDialog(this, "Error archiving patient: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }
