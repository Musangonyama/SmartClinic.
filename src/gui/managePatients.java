    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        String search = txtSearch.getText().trim();
        
        if(search.isEmpty()){
            loadPatients();
            return;
        }
        DefaultTableModel model = (DefaultTableModel)tblPatients.getModel();
        model.setRowCount(0);
        
        String sql = "SELECT PatientID, FullName, NationalID, Phone, Status "
                + "From Patients "
                + "WHERE Status = 'Active' "
                + "AND ("
                + "CAST(PatientID AS TEXT) LIKE ? "
                + "OR FullName LIKE ? "
                + "OR Phone LIKE ? "
                + "OR NationalID LIKE ?"
                + ") "
                + "ORDER BY FullName";
        try{
            Connection conn = DBConnection.getConnection();
            PreparedStatement pst = conn.prepareStatement(sql);
            String searchValue = "%" + search + "%";
            pst.setString(1, searchValue);
            pst.setString(2, searchValue);
            pst.setString(3, searchValue);
            pst.setString(4, searchValue);
            
            ResultSet rs = pst.executeQuery();
            
            boolean found = false;
            
           
int number = 1;

while (rs.next()) {

    found = true;

    String patientID = String.format(
            "%03d", rs.getInt("PatientID")
    );

    model.addRow(new Object[]{
        number,
        patientID,
        rs.getString("FullName"),
        rs.getString("NationalID"),
        rs.getString("Phone"),
        rs.getString("Status")
    });

    number++;
}

            if(!found){
                JOptionPane.showMessageDialog(this, "No active patient found.");
            }
            rs.close();
            pst.close();
            conn.close();
            
        }catch(SQLException e){
            JOptionPane.showMessageDialog(this, "Error searching patient: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSearchActionPerformed

