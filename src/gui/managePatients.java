private void restorePatient() {

    int selectedRow = tblPatients.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(
                this,
                "Please select an archived patient to restore."
        );
        return;
    }

    int patientID = Integer.parseInt(
            tblPatients.getValueAt(selectedRow, 1).toString()
    );

    String patientName =
            tblPatients.getValueAt(selectedRow, 2).toString();

    int confirmation = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to restore "
                    + patientName
                    + "?\n\nThe patient will become active again.",
            "Restore Patient",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.QUESTION_MESSAGE
    );

    if (confirmation != JOptionPane.YES_OPTION) {
        return;
    }

    String sql = "UPDATE Patients "
            + "SET Status = 'Active' "
            + "WHERE PatientID = ? AND Status = 'Archived'";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        pst.setInt(1, patientID);

        int rowsUpdated = pst.executeUpdate();

        if (rowsUpdated > 0) {

            AuditLogger.log(
                    "Patient restored",
                    "Patient " + patientName + " restored"
            );

            JOptionPane.showMessageDialog(
                    this,
                    patientName + " has been restored successfully."
            );

            loadPatients();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "The patient could not be restored. "
                    + "They may no longer be archived."
            );
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error restoring patient: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}


