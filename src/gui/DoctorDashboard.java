 private void completeConsultation() {

    if (selectedPatientID == -1 || selectedReferralID == -1) {

        JOptionPane.showMessageDialog(
                this,
                "Please select a referred patient first.",
                "No Patient Selected",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Complete this consultation and call the next patient?",
            "Complete Consultation",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    Connection conn = null;

    try {

        conn = DBConnection.getConnection();

        // ---------------------------------------------------------
        // Get the queue number belonging to this referral
        // ---------------------------------------------------------
        String getReferralSQL =
                "SELECT QueueNumber "
                + "FROM DoctorReferrals "
                + "WHERE ReferralID = ? "
                + "AND DoctorID = ? "
                + "AND Status = 'IN CONSULTATION'";

        PreparedStatement getReferralPst =
                conn.prepareStatement(getReferralSQL);

        getReferralPst.setInt(1, selectedReferralID);
        getReferralPst.setInt(2, UserSession.staffID);

        ResultSet rs = getReferralPst.executeQuery();

        String queueNumber = null;

        if (rs.next()) {
            queueNumber = rs.getString("QueueNumber");
        }

        rs.close();
        getReferralPst.close();

        // Referral was not found or is no longer in consultation
        if (queueNumber == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "The consultation could not be completed.\n\n"
                    + "The referral may no longer be assigned to this doctor "
                    + "or may not be IN CONSULTATION.",
                    "Completion Error",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        // ---------------------------------------------------------
        // Start transaction
        // ---------------------------------------------------------
        conn.setAutoCommit(false);

        // ---------------------------------------------------------
        // 1. Complete the Doctor Referral
        // ---------------------------------------------------------
        String referralSQL =
                "UPDATE DoctorReferrals "
                + "SET Status = 'COMPLETED' "
                + "WHERE ReferralID = ? "
                + "AND DoctorID = ? "
                + "AND Status = 'IN CONSULTATION'";

        PreparedStatement referralPst =
                conn.prepareStatement(referralSQL);

        referralPst.setInt(1, selectedReferralID);
        referralPst.setInt(2, UserSession.staffID);

        int referralUpdated = referralPst.executeUpdate();

        referralPst.close();

        if (referralUpdated == 0) {

            conn.rollback();

            JOptionPane.showMessageDialog(
                    this,
                    "The consultation could not be completed.\n\n"
                    + "The referral may no longer be assigned to this doctor "
                    + "or may not be IN CONSULTATION.",
                    "Completion Error",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        // ---------------------------------------------------------
        // 2. Complete the matching Queue record
        // ---------------------------------------------------------
        String queueSQL =
                "UPDATE Queue "
                + "SET status = 'COMPLETED' "
                + "WHERE PatientID = ? "
                + "AND queueNumber = ? "
                + "AND QueueDate = date('now', 'localtime') "
                + "AND UPPER(status) = 'IN CONSULTATION'";

        PreparedStatement queuePst =
                conn.prepareStatement(queueSQL);

        queuePst.setInt(1, selectedPatientID);
        queuePst.setString(2, queueNumber);

        int queueUpdated = queuePst.executeUpdate();

        queuePst.close();

        // ---------------------------------------------------------
        // If a queue record existed but could not be updated,
        // roll everything back.
        // ---------------------------------------------------------
        if (queueUpdated == 0) {

            conn.rollback();

            JOptionPane.showMessageDialog(
                    this,
                    "The consultation could not be completed because "
                    + "the patient's queue record could not be updated.",
                    "Completion Error",
                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }

        // ---------------------------------------------------------
        // Everything succeeded
        // ---------------------------------------------------------
        conn.commit();
        conn.setAutoCommit(true);

        // Refresh referrals and dashboard counts
        loadReferrals();

        if (tblReferrals.getRowCount() > 0) {

            tblReferrals.setRowSelectionInterval(0, 0);

            selectedReferral();

            String patientName = lblPatName.getText();
            String room = UserSession.room;
            String nextQueueNumber = "";

            int selectedRow = tblReferrals.getSelectedRow();

            if (selectedRow >= 0) {
                nextQueueNumber =
                        tblReferrals.getValueAt(selectedRow, 1).toString();
            }

            String message;

            if (!nextQueueNumber.isEmpty()) {

                message =
                        "Queue number " + nextQueueNumber
                        + ", patient " + patientName
                        + ", please proceed to " + room;

            } else {

                message =
                        "Patient " + patientName
                        + ", please proceed to " + room;
            }

            speakAnnouncement(message);

            JOptionPane.showMessageDialog(
                    this,
                    "Consultation completed.\n\n"
                    + "Next patient has been selected.",
                    "Next Patient",
                    JOptionPane.INFORMATION_MESSAGE
            );

            btnSave.setEnabled(false);
            btnPrescribe.setEnabled(false);
            btnComplete.setEnabled(false);

        } else {

            selectedReferralID = -1;
            selectedPatientID = -1;

            lblPatID.setText("");
            lblPatName.setText("");
            lblDOB.setText("");
            lblReason.setText("");
            lblStatus.setText("");

            txtDiag.setText("");
            txtTreatment.setText("");

            jFollow.setDate(null);

            btnOpen.setEnabled(false);
            btnSave.setEnabled(false);
            btnComplete.setEnabled(false);
            btnPrescribe.setEnabled(false);

            JOptionPane.showMessageDialog(
                    this,
                    "Consultation completed.\n\n"
                    + "There are no more patients waiting for the doctor.",
                    "Queue Complete",
                    JOptionPane.INFORMATION_MESSAGE
            );
        }

    } catch (SQLException e) {

        try {
            if (conn != null) {
                conn.rollback();
            }
        } catch (SQLException rollbackError) {
            System.out.println(
                    "Rollback error: "
                    + rollbackError.getMessage()
            );
        }

        JOptionPane.showMessageDialog(
                this,
                "Error completing consultation: "
                + e.getMessage(),
                "Completion Error",
                JOptionPane.ERROR_MESSAGE
        );

    } finally {

        try {
            if (conn != null) {
                conn.setAutoCommit(true);
                conn.close();
            }
        } catch (SQLException closeError) {
            System.out.println(
                    "Connection close error: "
                    + closeError.getMessage()
            );
        }
    }
}
