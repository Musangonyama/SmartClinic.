    private void loadReferrals(){
        DefaultTableModel model = (DefaultTableModel)tblReferrals.getModel();
        model.setRowCount(0);
        String sql =
        "SELECT r.ReferralID, "
        + "r.QueueNumber, "
        + "p.FullName AS PatientName, "
        + "r.Reason, "
        + "r.ReferralDate, "
        + "r.VisitType, "
        + "r.Status "
        + "FROM DoctorReferrals r "
        + "JOIN Patients p ON r.PatientID = p.PatientID "
        + "WHERE r.Status IN ('PENDING', 'IN CONSULTATION') "
        + "AND r.ToDepartment = ? "
        + "AND r.QueueDate = date('now', 'localtime') "
        + "ORDER BY r.CheckInTime ASC, r.ReferralID ASC";
        try{
            Connection conn = DBConnection.getConnection();
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, UserSession.department);
            ResultSet rs = pst.executeQuery();
            
            while(rs.next()){
                model.addRow(new Object[]{
                    rs.getInt("ReferralID"),
                    rs.getInt("QueueNumber"),
                    rs.getString("PatientName"),
                    rs.getString("Reason"),
                    rs.getString("ReferralDate"),
                    rs.getString("VisitType"),
                    rs.getString("Status")
                });
            }
            rs.close();
            pst.close();
            conn.close();
            updateDashboardCounts();
        }catch(SQLException e){
            JOptionPane.showMessageDialog(this, "Error loading doctor referrals: " + e.getMessage(), "Referral Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    private void selectedReferral() {

    int selectedRow = tblReferrals.getSelectedRow();

    if (selectedRow == -1) {
        return;
    }

    try {

        int referralID =
                Integer.parseInt(
                        tblReferrals.getValueAt(selectedRow, 0).toString()
                );

        String queueNumber =
                tblReferrals.getValueAt(selectedRow, 1).toString();

        String patientName =
                tblReferrals.getValueAt(selectedRow, 2).toString();

        String reason =
                tblReferrals.getValueAt(selectedRow, 3).toString();

        String status =
                tblReferrals.getValueAt(selectedRow, 6).toString();

        selectedReferralID = referralID;

        // Get patient ID from the database
        String sql =
                "SELECT PatientID "
                + "FROM DoctorReferrals "
                + "WHERE ReferralID = ?";

        Connection conn = DBConnection.getConnection();

        PreparedStatement pst =
                conn.prepareStatement(sql);

        pst.setInt(1, referralID);

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {

            selectedPatientID =
                    rs.getInt("PatientID");
        }

        rs.close();
        pst.close();
        conn.close();

        // ---------------------------------------------------------
        // Display selected patient information
        // ---------------------------------------------------------

        lblPatID.setText(
                "P" + String.format("%04d", selectedPatientID)
        );

        lblPatName.setText(patientName);

        lblReason.setText(reason);

        lblStatus.setText(status);

        // ---------------------------------------------------------
        // Button control
        // ---------------------------------------------------------

        if ("PENDING".equalsIgnoreCase(status)) {

            // Patient has not been taken yet
            btnOpen.setEnabled(true);
            btnSave.setEnabled(false);
            btnPrescribe.setEnabled(false);
            btnComplete.setEnabled(false);

        } else if ("IN CONSULTATION".equalsIgnoreCase(status)) {

            // Patient is currently with the doctor
            btnOpen.setEnabled(false);
            btnSave.setEnabled(true);
            btnPrescribe.setEnabled(true);
            btnComplete.setEnabled(false);

        } else {

            // Completed / cancelled / any other status
            btnOpen.setEnabled(false);
            btnSave.setEnabled(false);
            btnPrescribe.setEnabled(false);
            btnComplete.setEnabled(false);
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error selecting referral: "
                + e.getMessage(),
                "Referral Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}
