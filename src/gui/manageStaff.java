    private void btnAddStaffActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddStaffActionPerformed
        // TODO add your handling code here:
        String fullName = txtName.getText();
        String username = txtUsername.getText();
        String password = new String(txtPassword.getPassword());
        String role = cmbRole.getSelectedItem().toString();
        String status = cmbStatus.getSelectedItem().toString();
        String department = cmbDep.getSelectedItem().toString();
        String room = cmbRoom.getSelectedItem().toString();
        
  
if (isRoomOccupied(room, -1)) {
    JOptionPane.showMessageDialog(
            this,
            room + " is already assigned to another staff member."
    );
    return;
}
     
if (fullName.trim().isEmpty()
        || username.trim().isEmpty()
        || password.trim().isEmpty()) {

    JOptionPane.showMessageDialog(
            this,
            "Please fill in all required fields."
    );
    return;
}

if (cmbRole.getSelectedIndex() == 0) {
    JOptionPane.showMessageDialog(this, "Please choose a role.");
    return;
}

if (cmbDep.getSelectedIndex() == 0
        || cmbDep.getSelectedItem().toString().trim().isEmpty()) {

    JOptionPane.showMessageDialog(this, "Please choose Department.");
    return;
}

if (cmbRoom.getSelectedIndex() == 0) {
    JOptionPane.showMessageDialog(this, "Please Choose Room Number.");
    return;
}

        String sql = "INSERT INTO Staff "
                + "(FullName, Username, Password, Role, Status, Department, Room ) "
                + "VALUES (?, ?, ?, ?, ?, ?, ?)";
        
        try{
            Connection conn = DBConnection.getConnection();
            PreparedStatement pst = conn.prepareStatement(sql);
            
            pst.setString(1, fullName);
            pst.setString(2, username);
            pst.setString(3, password);
            pst.setString(4, role);
            pst.setString(5, status);
            pst.setString(6, department);
            pst.setString(7, room);
            
            pst.executeUpdate();
            AuditLogger.log("New staff added", fullName + " added in department/n"+ department);
            
            JOptionPane.showMessageDialog(this, "Staff added successfully!");
            
            clearField();
            loadStaff();
        } catch(SQLException e) {
            JOptionPane.showMessageDialog(this, "Error adding staff: " + e.getMessage());
        }
    }//GEN-LAST:event_btnAddStaffActionPerformed

