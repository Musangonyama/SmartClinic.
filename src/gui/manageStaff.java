    private void loadStaff() {

    DefaultTableModel model =
            (DefaultTableModel) tblStaff.getModel();

    model.setRowCount(0);

    String sql =
            "SELECT StaffID, FullName, Username, Role, Status, " +
            "Department, Room " +
            "FROM Staff " +
            "ORDER BY StaffID";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getInt("StaffID"),
                rs.getString("FullName"),
                rs.getString("Username"),
                rs.getString("Role"),
                rs.getString("Status"),
                rs.getString("Department"),
                rs.getString("Room")
            });
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error loading staff: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

private void editStaff() {

    int selectedRow = tblStaff.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a staff member from the table."
        );
        return;
    }

    int staffID = Integer.parseInt(
            tblStaff.getValueAt(selectedRow, 0).toString()
    );

    String fullName = txtName.getText().trim();
    String username = txtUsername.getText().trim();
    String password = new String(txtPassword.getPassword());
    String role = cmbRole.getSelectedItem().toString();
    String status = cmbStatus.getSelectedItem().toString();
    String department = cmbDep.getSelectedItem().toString();
    String room = cmbRoom.getSelectedItem().toString();

    
if (fullName.trim().isEmpty() || username.trim().isEmpty()) {
    JOptionPane.showMessageDialog(
            this,
            "Please enter the Full Name and Username."
    );
    return;
}

if (isRoomOccupied(room, staffID)) {
    JOptionPane.showMessageDialog(
            this,
            room + " is already assigned to another staff member."
    );
    return;
}


if (cmbRole.getSelectedIndex() == 0) {
    JOptionPane.showMessageDialog(this, "Please choose a valid role.");
    return;
}

if (cmbDep.getSelectedIndex() == 0
        || cmbDep.getSelectedItem().toString().trim().isEmpty()) {

    JOptionPane.showMessageDialog(this, "Please choose a valid department.");
    return;
}

if (cmbRoom.getSelectedIndex() == 0) {
    JOptionPane.showMessageDialog(this, "Please choose a valid room number.");
    return;
}


    String sql;

    if (password.isEmpty()) {
        sql = "UPDATE Staff SET "
                + "FullName = ?, Username = ?, Role = ?, "
                + "Status = ?, Department = ?, Room = ? "
                + "WHERE StaffID = ?";
    } else {
        sql = "UPDATE Staff SET "
                + "FullName = ?, Username = ?, Password = ?, "
                + "Role = ?, Status = ?, Department = ?, Room = ? "
                + "WHERE StaffID = ?";
    }

    int updated;

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        if (password.isEmpty()) {
            pst.setString(1, fullName);
            pst.setString(2, username);
            pst.setString(3, role);
            pst.setString(4, status);
            pst.setString(5, department);
            pst.setString(6, room);
            pst.setInt(7, staffID);
        } else {
            pst.setString(1, fullName);
            pst.setString(2, username);
            pst.setString(3, password);
            pst.setString(4, role);
            pst.setString(5, status);
            pst.setString(6, department);
            pst.setString(7, room);
            pst.setInt(8, staffID);
        }

        updated = pst.executeUpdate();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Error updating staff: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    if (updated > 0) {
        AuditLogger.log(
                "Staff details updated",
                fullName + "'s details updated"
        );

        JOptionPane.showMessageDialog(
                this,
                "Staff details updated successfully!"
        );

        clearField();
        loadStaff();

    } else {
        JOptionPane.showMessageDialog(
                this,
                "No staff record was updated."
        );
    }
}

