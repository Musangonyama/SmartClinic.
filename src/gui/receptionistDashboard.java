    private void announceEmergency() {
    try {
        String message = "Emergency case. Nurse assistance required.";

        String command = "Add-Type -AssemblyName System.Speech; "
                + "$speak = New-Object System.Speech.Synthesis.SpeechSynthesizer; "
                + "$speak.Speak('" + message + "');";

        new ProcessBuilder(
                "powershell.exe",
                "-Command",
                command
        ).start();

    } catch (Exception e) {
        e.printStackTrace();
    }
}
    private void loadStatistics() {

    Connection conn = null;
    PreparedStatement pst = null;
    ResultSet rs = null;

    try {

        conn = DBConnection.getConnection();


        String sqlPatientsToday =
                "SELECT COUNT(*) AS total " +
                "FROM Queue " +
                "WHERE QueueDate = date('now','localtime')";

        pst = conn.prepareStatement(sqlPatientsToday);
        rs = pst.executeQuery();

        if (rs.next()) {
            lblToday.setText(String.valueOf(rs.getInt("total")));
        }

        rs.close();
        pst.close();

        String sqlAppointmentsToday =
                "SELECT COUNT(*) AS total " +
                "FROM Appointments " +
                "WHERE AppointmentDate = date('now','localtime') " +
                "AND UPPER(Status) NOT IN ('CANCELED', 'CANCELLED', 'NO-SHOW')";

        pst = conn.prepareStatement(sqlAppointmentsToday);
        rs = pst.executeQuery();

        if (rs.next()) {
            lblApps.setText(String.valueOf(rs.getInt("total")));
        }

        rs.close();
        pst.close();


        String sqlWalkInsToday =
                "SELECT COUNT(*) AS total " +
                "FROM Queue " +
                "WHERE QueueDate = date('now','localtime') " +
                "AND AppointmentID IS NULL";

        pst = conn.prepareStatement(sqlWalkInsToday);
        rs = pst.executeQuery();

        if (rs.next()) {
            lblWaiting.setText(String.valueOf(rs.getInt("total")));
        }

        rs.close();
        pst.close();



        String sqlWaitingNow =
                "SELECT COUNT(*) AS total " +
                "FROM Queue " +
                "WHERE QueueDate = date('now','localtime') " +
                "AND UPPER(Status) = 'WAITING'";

        pst = conn.prepareStatement(sqlWaitingNow);
        rs = pst.executeQuery();

        if (rs.next()) {
            lblEmerg.setText(String.valueOf(rs.getInt("total")));
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Could not load dashboard statistics:\n"
                + e.getMessage(),
                "Statistics Error",
                JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();

    } finally {

        try {
            if (rs != null) {
                rs.close();
            }
        } catch (Exception e) {
        }

        try {
            if (pst != null) {
                pst.close();
            }
        } catch (Exception e) {
        }

        try {
            if (conn != null) {
                conn.close();
            }
        } catch (Exception e) {
        }
    }
}
