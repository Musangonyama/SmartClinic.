    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        String searchText = txtSearch.getText().trim();
        if(searchText.isEmpty()){
           JOptionPane.showMessageDialog(this,"Please enter a patient ID.");
           return;
        }
        String sql = "SELECT PatientID, FullName, DateOfBirth, MedicalRecordNo "
                + "FROM Patients "
                + "WHERE PatientID = ?";
        
        try{
            Connection conn = DBConnection.getConnection();
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setInt(1, Integer.parseInt(searchText));
            ResultSet rs = pst.executeQuery();
            
            if(rs.next()){
                registeredPatientID = rs.getInt("PatientID");
                registeredPatientName = rs.getString("FullName");
                registeredPatientDOB = rs.getString("DateOfBirth");
                registeredMedicalRecordNo = rs.getString("MedicalRecordNo");
                
                lblPatientID.setText(String.valueOf(registeredPatientID));
                lblFullName.setText(registeredPatientName);
                lblDOB.setText(registeredPatientDOB);
                lblMedicalRecordNo.setText(registeredMedicalRecordNo);
                
                JOptionPane.showMessageDialog(this, "Patient found successfully!");
            }else{
                registeredPatientID = -1;
                lblPatientID.setText("-");
                lblFullName.setText("-");
                lblDOB.setText("-");
                lblMedicalRecordNo.setText("-");
                
                JOptionPane.showMessageDialog(this, "Patient ID must be a number.");
            }

        }catch(SQLException e){
            JOptionPane.showMessageDialog(this, "Error searching patient: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSearchActionPerformed

