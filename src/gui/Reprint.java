    /**
     * DRAW INSIDE APPOINTMENT PAGE
     */
    private void drawInsidePage(
            Graphics2D g2,
            double pageWidth,
            double pageHeight) {

        int margin = 50;

        /*
         * --------------------------------------------------
         * TITLE
         * --------------------------------------------------
         */
        g2.setFont(
                new Font(
                        "Arial",
                        Font.BOLD,
                        24
                )
        );

        String title =
                "APPOINTMENT RECORD";

        g2.drawString(
                title,
                margin + 150,
                margin + 40
        );

        /*
         * --------------------------------------------------
         * TABLE
         * --------------------------------------------------
         */
        int tableX = margin + 80;
        int tableY = margin + 80;

        int tableWidth =
                (int) pageWidth - margin * 2 - 160;

        int rowHeight = 45;

        // Two columns
        int dateColumnWidth =
                tableWidth / 2;

        int timeColumnWidth =
                tableWidth - dateColumnWidth;

        int numberOfRows = 9;

        /*
         * Draw table outer border
         */
        g2.drawRect(
                tableX,
                tableY,
                tableWidth,
                rowHeight * numberOfRows
        );

        /*
         * Draw vertical line
         */
        g2.drawLine(
                tableX + dateColumnWidth,
                tableY,
                tableX + dateColumnWidth,
                tableY + rowHeight * numberOfRows
        );

        /*
         * Draw horizontal lines
         */
        for (int i = 1; i < numberOfRows; i++) {

            int y =
                    tableY + rowHeight * i;

            g2.drawLine(
                    tableX,
                    y,
                    tableX + tableWidth,
                    y
            );
        }

        /*
         * --------------------------------------------------
         * TABLE HEADERS
         * --------------------------------------------------
         */
        g2.setFont(
                new Font(
                        "Arial",
                        Font.BOLD,
                        14
                )
        );

        g2.drawString(
                "DATE",
                tableX + 40,
                tableY + 29
        );

        g2.drawString(
                "TIME",
                tableX + dateColumnWidth + 40,
                tableY + 29
        );

        /*
         * --------------------------------------------------
         * FOOTER
         * --------------------------------------------------
         */
        g2.setFont(
                new Font(
                        "Arial",
                        Font.ITALIC,
                        11
                )
        );

        g2.drawString(
                "Appointment date and time are written by clinic staff.",
                margin + 80,
                tableY + rowHeight * numberOfRows + 35
        );
    }

    /**
     * CREATE QR IMAGE FOR PRINTING
     */
    private BufferedImage createQRCodeImage(
            int patientID,
            int width,
            int height) {

        try {

            String qrData =
                    "SMARTCLINIC:PATIENT:" + patientID;

            QRCodeWriter qrCodeWriter =
                    new QRCodeWriter();

            BitMatrix bitMatrix =
                    qrCodeWriter.encode(
                            qrData,
                            BarcodeFormat.QR_CODE,
                            width,
                            height
                    );

            return MatrixToImageWriter.toBufferedImage(
                    bitMatrix
            );

        } catch (WriterException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error creating QR Code: "
                    + e.getMessage()
            );

            return null;
        }
    }

