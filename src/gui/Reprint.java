     private void printPatientCard(){
          PrinterJob printerJob =
                PrinterJob.getPrinterJob();

        printerJob.setJobName(
                "Smart Clinic Patient Booklet"
        );

        printerJob.setPrintable(
                new Printable() {

                    @Override
                    public int print(
                            Graphics graphics,
                            PageFormat pageFormat,
                            int pageIndex)
                            throws PrinterException {

                        // We only have two pages
                        if (pageIndex > 1) {
                            return NO_SUCH_PAGE;
                        }

                        Graphics2D g2 =
                                (Graphics2D) graphics;

                        // Translate to printable area
                        g2.translate(
                                pageFormat.getImageableX(),
                                pageFormat.getImageableY()
                        );

                        double pageWidth =
                                pageFormat.getImageableWidth();

                        double pageHeight =
                                pageFormat.getImageableHeight();

                        /*
                         * ======================================
                         * PAGE 1 - OUTSIDE
                         * ======================================
                         */
                        if (pageIndex == 0) {

                            drawOutsidePage(
                                    g2,
                                    pageWidth,
                                    pageHeight
                            );

                            return PAGE_EXISTS;
                        }

                        /*
                         * ======================================
                         * PAGE 2 - INSIDE
                         * ======================================
                         */
                        if (pageIndex == 1) {

                            drawInsidePage(
                                    g2,
                                    pageWidth,
                                    pageHeight
                            );

                            return PAGE_EXISTS;
                        }

                        return NO_SUCH_PAGE;
                    }
                }
        );

        // Show printer selection dialog
        boolean print =
                printerJob.printDialog();

        if (print) {

            try {

                printerJob.print();

                JOptionPane.showMessageDialog(
                        this,
                        "Patient booklet sent to printer."
                );

            } catch (PrinterException e) {

                JOptionPane.showMessageDialog(
                        this,
                        "Error printing patient booklet: "
                        + e.getMessage()
                );
            }
        }
    }
