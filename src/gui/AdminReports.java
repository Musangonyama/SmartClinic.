private int getCount(
        Connection conn,
        String sql,
        LocalDate startDate,
        LocalDate endDate,
        String department) throws SQLException {

    PreparedStatement pst = conn.prepareStatement(sql);

    int index = 1;

    pst.setString(index++, startDate.toString());
    pst.setString(index++, endDate.toString());

    if (!department.equals("All Departments")) {
        pst.setString(index, department);
    }

    ResultSet rs = pst.executeQuery();

    int count = 0;

    if (rs.next()) {
        count = rs.getInt("total");
    }

    rs.close();
    pst.close();

    return count;
}
private void loadStaffActivity() {

    DefaultTableModel model =
            (DefaultTableModel) tblStaffActivity.getModel();

    model.setRowCount(0);

    String sql =
        "SELECT s.FullName, s.Role, COUNT(q.queueID) " +
        "FROM Queue q " +
        "JOIN Staff s ON q.StaffID = s.StaffID " +
        "WHERE q.status = 'COMPLETED' " +
        "AND strftime('%Y-%m', q.QueueDate) = " +
        "strftime('%Y-%m', 'now', 'localtime') " +
        "GROUP BY s.StaffID " +
        "ORDER BY COUNT(q.queueID) DESC";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getString("FullName"),
                rs.getString("Role"),
                rs.getInt(3)
            });
        }

    } catch (SQLException e) {
        e.printStackTrace();
    }
}
