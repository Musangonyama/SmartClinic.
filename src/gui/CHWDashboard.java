   private void loadCHWStatistics() {

    int chwID = UserSession.staffID;

    String sql =
        "SELECT " +
        "COUNT(*) AS AssignedCases, " +
        "SUM(CASE WHEN date(ExpectedVisitDate) < date('now') " +
        "AND Status = 'ASSIGNED' THEN 1 ELSE 0 END) AS MissedVisits, " +
        "SUM(CASE WHEN Status = 'IN PROGRESS' THEN 1 ELSE 0 END) AS InProgress, " +
        "SUM(CASE WHEN Status = 'ESCALATED' THEN 1 ELSE 0 END) AS Escalated " +
        "FROM ChronicFollowUp " +
        "WHERE AssignedCHWID = ? " +
        "AND Status IN ('ASSIGNED', 'IN PROGRESS', 'ESCALATED')";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, chwID);

        try (ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {

                 lblAssignedCases.setText(String.valueOf(rs.getInt("AssignedCases")));

                lblMissedVisits.setText(
                    String.valueOf(rs.getInt("MissedVisits"))
                );

                lblInProgress.setText(
                    String.valueOf(rs.getInt("InProgress"))
                );

                lblEscalated.setText(
                    String.valueOf(rs.getInt("Escalated"))
                );
            }
        }

    } catch (SQLException e) {

        e.printStackTrace();

        lblAssignedCases.setText("0");
        lblMissedVisits.setText("0");
        lblInProgress.setText("0");
        lblEscalated.setText("0");
    }
}
