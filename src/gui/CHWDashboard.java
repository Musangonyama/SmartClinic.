   private void loadCHWFollowUps() {

    DefaultTableModel model =
            (DefaultTableModel) tblFollowUps.getModel();

    model.setRowCount(0);

    int chwID = UserSession.staffID;

    String sql =
        "SELECT cf.FollowUpID, " +
        "p.PatientID, " +
        "p.FullName, " +
        "cf.ExpectedVisitDate, " +
        "p.Address, " +
        "cf.Status " +
        "FROM ChronicFollowUp cf " +
        "JOIN Patients p ON cf.PatientID = p.PatientID " +
        "WHERE cf.AssignedCHWID = ? " +
        "AND cf.Status IN ('ASSIGNED', 'IN PROGRESS', 'ESCALATED') " +
        "ORDER BY date(cf.ExpectedVisitDate) ASC";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, chwID);

        try (ResultSet rs = pst.executeQuery()) {

            int caseCount = 0;

            while (rs.next()) {

                int followUpID =
                        rs.getInt("FollowUpID");

                int patientID =
                        rs.getInt("PatientID");

                String patientName =
                        rs.getString("FullName");

                String expectedDate =
                        rs.getString("ExpectedVisitDate");
                String address = rs.getString("Address");

                String status =
                        rs.getString("Status");

                long daysMissed =
                        calculateDaysMissed(expectedDate);

                model.addRow(new Object[]{
                   followUpID,
                    patientID,
                    patientName,
                    expectedDate,
                    daysMissed + " days",
                    address,
                    status
                });
                
                caseCount++;
            }

           
        }

    } catch (SQLException e) {

        e.printStackTrace();

       JOptionPane.showMessageDialog(
        this,
        "Error loading CHW follow-ups:\n"
        + e.getMessage(),
        "Database Error",
        JOptionPane.ERROR_MESSAGE
);

        
    }
}
   private long calculateDaysMissed(String expectedDate) {

    try {

        LocalDate expected =
                LocalDate.parse(expectedDate);

        LocalDate today =
                LocalDate.now();

        long days =
                ChronoUnit.DAYS.between(
                        expected,
                        today
                );

        return Math.max(days, 0);

    } catch (Exception e) {

        return 0;
    }
}
