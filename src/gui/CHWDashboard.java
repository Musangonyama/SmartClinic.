    private void btnOpenActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnOpenActionPerformed
        // TODO add your handling code here:
 
    int selectedRow = tblFollowUps.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(
            this,
            "Please select a patient first.",
            "No Patient Selected",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    int modelRow =
            tblFollowUps.convertRowIndexToModel(selectedRow);

    DefaultTableModel model =
            (DefaultTableModel) tblFollowUps.getModel();

    int followUpID =
            ((Number) model.getValueAt(modelRow, 0)).intValue();

    int patientID =
            ((Number) model.getValueAt(modelRow, 1)).intValue();

    String status =
            String.valueOf(model.getValueAt(modelRow, 6));

    // Do not allow the CHW to reopen escalated cases
    if ("ESCALATED".equalsIgnoreCase(status)) {

        JOptionPane.showMessageDialog(
            this,
            "This case has already been escalated to the nurse.\n"
            + "You cannot open it for CHW follow-up.",
            "Case Escalated",
            JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    // Do not allow completed cases to be reopened
    if ("COMPLETE".equalsIgnoreCase(status)) {

        JOptionPane.showMessageDialog(
            this,
            "This follow-up has already been completed.",
            "Case Completed",
            JOptionPane.INFORMATION_MESSAGE
        );

        return;
    }

    CHWFollowUp page =
            new CHWFollowUp(followUpID, patientID);

    page.setLocationRelativeTo(null);
    page.setVisible(true);

    }//GEN-LAST:event_btnOpenActionPerformed

