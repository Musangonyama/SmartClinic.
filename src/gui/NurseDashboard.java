private void checkForEmergency() {

    String sql =
            "SELECT EmergencyID "
            + "FROM EmergencyAlerts "
            + "WHERE UPPER(TRIM(Status)) = 'ACTIVE' "
            + "ORDER BY EmergencyID DESC "
            + "LIMIT 1";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        if (rs.next()) {

            int emergencyID = rs.getInt("EmergencyID");

            // Only alert once for each new emergency.
            if (emergencyID != lastEmergencyID) {

                lastEmergencyID = emergencyID;

                btnEmergency.setEnabled(true);

                speakAnnouncement(
                        "Emergency case. Nurse assistance required."
                );

                JOptionPane.showMessageDialog(
                        this,
                        "EMERGENCY CASE\n\n"
                        + "Nurse assistance is required.\n\n"
                        + "Please respond to the emergency.",
                        "Emergency Alert",
                        JOptionPane.WARNING_MESSAGE
                );
            } else {
                // Emergency already detected.
                // Keep the button enabled until the nurse responds.
                btnEmergency.setEnabled(true);
            }

        } else {

            // No active emergency exists.
            btnEmergency.setEnabled(false);
            lastEmergencyID = -1;
        }

    } catch (SQLException e) {

        System.out.println(
                "Emergency check error: " + e.getMessage()
        );
    }
}

    private void startEmergencyChecker() {

    emergencyTimer = new javax.swing.Timer(30000, e -> checkForEmergency());

    emergencyTimer.start();
}
    
