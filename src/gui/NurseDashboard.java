            + "SET Status = 'RESPONDED', "
            + "RespondedBy = ?, "
            + "RespondedAt = CURRENT_TIMESTAMP "
            + "WHERE EmergencyID = ? "
            + "AND UPPER(Status) = 'ACTIVE'";

