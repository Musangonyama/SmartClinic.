    private void btnSkipActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSkipActionPerformed
        // TODO add your handling code here:
         if (currentQueueID == -1) {
        JOptionPane.showMessageDialog(
            this,
            "There is no currently called patient to skip.",
            "No Patient Selected",
            JOptionPane.WARNING_MESSAGE
        );
        btnSkip.setEnabled(false);
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
        this,
        "Confirm that the patient is not present?\n"
        + "The patient will return to the waiting queue.",
        "Patient Not Present",
        JOptionPane.YES_NO_OPTION,
        JOptionPane.QUESTION_MESSAGE
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    String sql = "UPDATE Queue SET "
            + "Status = 'Waiting', "
            + "MissedCallCount = MissedCallCount + 1, "
            + "LastCalledAt = datetime('now','localtime'), "
            + "StaffID = NULL, "
            + "Room = NULL, "
            + "ConsultationStartTime = NULL "
            + "WHERE queueID = ? "
            + "AND Department = ? "
            + "AND QueueDate = date('now','localtime') "
            + "AND Status = 'In Consultation'";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pstmt = conn.prepareStatement(sql)) {

        pstmt.setInt(1, currentQueueID);
        pstmt.setString(2, UserSession.department);

        int rowsUpdated = pstmt.executeUpdate();

        if (rowsUpdated == 1) {
            JOptionPane.showMessageDialog(
                this,
                "Patient marked as not present.\n"
                + "The patient has been returned to the waiting queue.",
                "Patient Skipped",
                JOptionPane.INFORMATION_MESSAGE
            );

           
AuditLogger.log(
    "Patient Not Present",
    UserSession.fullName
    + " marked queue entry "
    + currentQueueID
    + " as patient not present. "
    + "The entry was returned to Waiting."
);

            currentQueueID = -1;
            selectedPatientID = -1;
            btnComplete.setEnabled(false);
            btnSkip.setEnabled(false);
            btnOpen.setEnabled(false);

            loadWaitingPatients();
            loadStatistics();

        } else {
            JOptionPane.showMessageDialog(
                this,
                "The queue entry could not be updated. "
                + "It may no longer be awaiting a response, "
                + "or it may belong to a different department.",
                "Update Failed",
                JOptionPane.WARNING_MESSAGE
            );
        }

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(
            this,
            "Error returning patient to the waiting queue:\n"
            + ex.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnSkipActionPerformed

