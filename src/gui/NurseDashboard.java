    private void btnCallActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCallActionPerformed
        // TODO add your handling code here:
   try {
        Connection conn = DBConnection.getConnection();

        /*
         * STEP 1: FIND THE NEXT ELIGIBLE PATIENT
         *
         * Patients who have not missed a call are prioritised.
         * Within that group, due appointments are prioritised
         * using the existing appointment-time rules.
         */
        String sql =
                "SELECT q.queueID, "
                + "q.queueNumber, "
                + "q.patientID, "
                + "p.FullName AS PatientName, "
                + "q.appointmentID, "
                + "q.checkInTime, "
                + "a.AppointmentDate, "
                + "a.AppointmentTime "
                + "FROM Queue q "
                + "JOIN Patients p "
                + "ON q.patientID = p.PatientID "
                + "LEFT JOIN Appointments a "
                + "ON q.appointmentID = a.AppointmentID "
                + "WHERE q.Department = ? "
                + "AND q.QueueDate = date('now', 'localtime') "
                + "AND q.Status = 'Waiting' "
                + "ORDER BY "
                + "q.MissedCallCount ASC, "
                + "CASE "
                + "WHEN q.appointmentID IS NOT NULL "
                + "AND datetime(a.AppointmentDate || ' ' || "
                + "a.AppointmentTime) <= datetime('now', 'localtime') "
                + "THEN 0 ELSE 1 "
                + "END, "
                + "CASE "
                + "WHEN q.appointmentID IS NOT NULL "
                + "AND datetime(a.AppointmentDate || ' ' || "
                + "a.AppointmentTime) <= datetime('now', 'localtime') "
                + "THEN datetime(a.AppointmentDate || ' ' || "
                + "a.AppointmentTime) "
                + "ELSE NULL "
                + "END ASC, "
                + "q.checkInTime ASC "
                + "LIMIT 1";

        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, UserSession.department);

        ResultSet rs = pst.executeQuery();

        if (!rs.next()) {
            rs.close();
            pst.close();
            conn.close();

            JOptionPane.showMessageDialog(
                    this,
                    "There are no more waiting patients.",
                    "Queue Empty",
                    JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }

        int queueID = rs.getInt("queueID");
        String queueNumber = rs.getString("queueNumber");
        int patientID = rs.getInt("patientID");
        String patientName = rs.getString("PatientName");

        rs.close();
        pst.close();

        /*
         * STEP 2: FIND THE LOGGED-IN NURSE
         */
        String staffSQL =
                "SELECT StaffID, Room "
                + "FROM Staff "
                + "WHERE FullName = ? "
                + "AND Role = 'Nurse' "
                + "AND Status = 'Active'";

        PreparedStatement staffPst =
                conn.prepareStatement(staffSQL);

        staffPst.setString(1, UserSession.fullName);

        ResultSet staffRs = staffPst.executeQuery();

        if (!staffRs.next()) {
            staffRs.close();
            staffPst.close();
            conn.close();

            JOptionPane.showMessageDialog(
                    this,
                    "Logged-in nurse could not be found.",
                    "Staff Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        int staffID = staffRs.getInt("StaffID");
        String room = staffRs.getString("Room");

        staffRs.close();
        staffPst.close();

        /*
         * STEP 3: CALL THE PATIENT
         *
         * Update the exact queue entry.
         * Record the time the patient was called.
         */
        String updateSQL =
                "UPDATE Queue "
                + "SET Status = 'In Consultation', "
                + "StaffID = ?, "
                + "Room = ?, "
                + "LastCalledAt = datetime('now', 'localtime'), "
                + "ConsultationStartTime = datetime('now', 'localtime') "
                + "WHERE queueID = ? "
                + "AND Department = ? "
                + "AND QueueDate = date('now', 'localtime') "
                + "AND Status = 'Waiting'";

        PreparedStatement updatePst =
                conn.prepareStatement(updateSQL);

        updatePst.setInt(1, staffID);
        updatePst.setString(2, room);
        updatePst.setInt(3, queueID);
        updatePst.setString(4, UserSession.department);

        int updated = updatePst.executeUpdate();

        updatePst.close();
        conn.close();

        /*
         * STEP 4: UPDATE THE DASHBOARD
         */
        if (updated > 0) {

            currentQueueID = queueID;
            selectedPatientID = patientID;

            lblQueueNo.setText(queueNumber);
            lblPatient.setText(patientName);
            lblStat.setText("IN CONSULTATION");
            btnComplete.setEnabled(true);
            btnOpen.setEnabled(true);
            btnSkip.setEnabled(true);

            loadWaitingPatients();
            loadStatistics();

            AuditLogger.log(
                    "Called Next Patient",
                    UserSession.fullName
                    + " called patient "
                    + patientName
                    + " (Patient ID: " + patientID + ")"
                    + " | Queue: " + queueNumber
                    + " | Room: " + room
            );

            String message =
                    "Queue number "
                    + queueNumber
                    + ", please proceed to "
                    + room;

            speakAnnouncement(message);

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "The next patient could not be called. "
                    + "The queue may have changed. "
                    + "Please refresh and try again.",
                    "Queue Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error calling the next patient: " + e.getMessage(),
                "Queue Error",
                JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }
    }//GEN-LAST:event_btnCallActionPerformed

