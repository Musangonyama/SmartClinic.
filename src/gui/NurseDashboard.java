private void completeConsultation() {
    if (currentQueueID == -1 || selectedPatientID == -1) {
        JOptionPane.showMessageDialog(
            this,
            "Please call a patient before completing a consultation.",
            "No Active Consultation",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to complete this consultation?",
        "Confirm Completion",
        JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    String sql =
        "UPDATE Queue " +
        "SET Status = 'Completed' " +
        "WHERE QueueID = ? " +
        "AND PatientID = ? " +
        "AND Status = 'In Consultation' " +
        "AND StaffID = ?";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, currentQueueID);
        pst.setInt(2, selectedPatientID);
        pst.setInt(3, UserSession.staffID);

        int updated = pst.executeUpdate();

        if (updated > 0) {
            AuditLogger.log(
                "Completed Consultation",
                UserSession.fullName
                + " completed the consultation for Patient ID: "
                + selectedPatientID
            );

            JOptionPane.showMessageDialog(
                this,
                "Consultation completed successfully."
            );

            currentQueueID = -1;
            selectedPatientID = -1;

            btnComplete.setEnabled(false);

            loadWaitingPatients();
            loadStatistics();
        } else {
            JOptionPane.showMessageDialog(
                this,
                "The consultation could not be completed. "
                + "Please confirm that you are assigned to this active consultation.",
                "Completion Failed",
                JOptionPane.WARNING_MESSAGE
            );
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Error completing consultation: " + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}

private void referCurrentPatientToDoctor() {

    // A referral must belong to the nurse's active consultation.
    if (currentQueueID == -1 || selectedPatientID == -1) {
        JOptionPane.showMessageDialog(
                this,
                "Please call a patient before referring them.",
                "No Active Consultation",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String reason = JOptionPane.showInputDialog(
            this,
            "Enter the reason for referring this patient to a doctor:",
            "Refer Patient to Doctor",
            JOptionPane.QUESTION_MESSAGE
    );

    if (reason == null) {
        return; // The nurse cancelled.
    }

    reason = reason.trim();

    if (reason.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Please enter a referral reason.",
                "Referral Reason Required",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    Connection conn = null;

    try {
        conn = DBConnection.getConnection();
        conn.setAutoCommit(false);

        // 1. Prevent a duplicate active referral today.
        String duplicateSQL =
                "SELECT ReferralID FROM DoctorReferrals "
                + "WHERE PatientID = ? "
                + "AND QueueDate = date('now', 'localtime') "
                + "AND Status IN ('PENDING', 'IN CONSULTATION') "
                + "LIMIT 1";

        try (PreparedStatement pst =
                     conn.prepareStatement(duplicateSQL)) {

            pst.setInt(1, selectedPatientID);

            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    conn.rollback();

                    JOptionPane.showMessageDialog(
                            this,
                            "This patient already has an active "
                            + "doctor referral today.",
                            "Existing Referral",
                            JOptionPane.WARNING_MESSAGE
                    );
                    return;
                }
            }
        }

        String department = UserSession.department;

        // 2. Generate the next department-based doctor queue number.
        int referralCount = 0;

        String countSQL =
                "SELECT COUNT(*) AS Total "
                + "FROM DoctorReferrals "
                + "WHERE ToDepartment = ? "
                + "AND QueueDate = date('now', 'localtime')";

        try (PreparedStatement pst =
                     conn.prepareStatement(countSQL)) {

            pst.setString(1, department);

            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    referralCount = rs.getInt("Total");
                }
            }
        }

        String queueNumber =
                getDepartmentPrefix(department)
                + "-D"
                + String.format("%03d", referralCount + 1);

        // 3. Save the referral as PENDING.
        String insertSQL =
                "INSERT INTO DoctorReferrals "
                + "(PatientID, NurseID, DoctorID, ReferralDate, "
                + "Reason, Status, Notes, ToDepartment, QueueNumber, "
                + "QueueDate, CheckInTime, VisitType) "
                + "VALUES (?, ?, NULL, date('now', 'localtime'), "
                + "?, 'PENDING', ?, ?, ?, "
                + "date('now', 'localtime'), "
                + "time('now', 'localtime'), 'Nurse Referral')";

        try (PreparedStatement pst =
                     conn.prepareStatement(insertSQL)) {

            pst.setInt(1, selectedPatientID);
            pst.setInt(2, UserSession.staffID);
            pst.setString(3, reason);
            pst.setString(
                    4,
                    "Referred by " + UserSession.fullName
            );
            pst.setString(5, department);
            pst.setString(6, queueNumber);

            pst.executeUpdate();
        }

        // 4. Complete the nurse's queue entry.
        // The doctor referral remains PENDING in DoctorReferrals.
        String updateSQL =
                "UPDATE Queue "
                + "SET Status = 'Completed' "
                + "WHERE QueueID = ? "
                + "AND PatientID = ? "
                + "AND Status = 'In Consultation' "
                + "AND StaffID = ?";

        try (PreparedStatement pst =
                     conn.prepareStatement(updateSQL)) {

            pst.setInt(1, currentQueueID);
            pst.setInt(2, selectedPatientID);
            pst.setInt(3, UserSession.staffID);

            int updated = pst.executeUpdate();

            if (updated != 1) {
                throw new SQLException(
                        "The nurse's active queue entry "
                        + "could not be completed."
                );
            }
        }

        // Save both changes together.
        conn.commit();

        int referredPatientID = selectedPatientID;
        int completedQueueID = currentQueueID;

        AuditLogger.log(
                "Referred Patient to Doctor",
                UserSession.fullName
                + " referred Patient ID: " + referredPatientID
                + " | Doctor Queue: " + queueNumber
                + " | Reason: " + reason
                + " | Nurse Queue ID completed: " + completedQueueID
        );

        // 5. Clear the nurse's active consultation.
        currentQueueID = -1;
        selectedPatientID = -1;

        btnComplete.setEnabled(false);
        btnOpen.setEnabled(false);
        btnSkip.setEnabled(false);
        btnReferDoctor.setEnabled(false);

        lblStat.setText("COMPLETED - REFERRED");
        lblQueueNo.setText("");
        lblPatient.setText("");

        loadWaitingPatients();
        loadStatistics();

        JOptionPane.showMessageDialog(
                this,
                "Patient referred successfully.\n\n"
                + "Doctor queue number: " + queueNumber
                + "\nReferral status: PENDING"
                + "\nNurse consultation: COMPLETED",
                "Referral Successful",
                JOptionPane.INFORMATION_MESSAGE
        );

    } catch (SQLException e) {

        if (conn != null) {
            try {
                conn.rollback();
            } catch (SQLException rollbackError) {
                rollbackError.printStackTrace();
            }
        }

        JOptionPane.showMessageDialog(
                this,
                "Could not refer the patient:\n" + e.getMessage(),
                "Referral Error",
                JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();

    } finally {
        if (conn != null) {
            try {
                conn.setAutoCommit(true);
                conn.close();
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
    }
}

private String getDepartmentPrefix(String department) {

    if (department == null) {
        return "GEN";
    }

    switch (department.trim().toUpperCase()) {
        case "GENERAL CONSULTATION":
            return "GC";
        case "MATERNAL HEALTH":
        case "MARTENAL HEALTH":
            return "MH";
        case "CHILD HEALTH":
            return "CH";
        case "CHRONIC CARE":
            return "CC";
        case "TB/RESPIRATORY":
            return "TB";
        case "MENTAL HEALTH":
            return "MHT";
        case "FAMILY PLANNING":
            return "FP";
        case "DENTAL":
            return "DEN";
        default:
            return "GEN";
    }
}
