    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        String search = txtSearch.getText().toString();
        
        if(search.isEmpty()){
            loadDefaultPatients();
            return;
        }
        DefaultTableModel model = (DefaultTableModel)tblPatients.getModel();
            model.setRowCount(0);
            
            String sql = "SELECT PatientID, FullName, NationalID, "
                    + "Phone, MedicalRecordNo "
                    + "FROM Patients "
                    + "WHERE CAST(PatientID AS TEXT) LIKE ? "
                    + "OR FullName LIKE ? "
                    + "OR NationalID LIKE ? "
                    + "OR Phone LIKE ? "
                    + "OR MedicalRecordNo LIKE ? ";
            
            try{
             Connection conn = DBConnection.getConnection();
             PreparedStatement pst = conn.prepareStatement(sql);
             
             String searchValue = "%" + search + "%";
             
             pst.setString(1, searchValue);
             pst.setString(2, searchValue);
             pst.setString(3, searchValue);
             pst.setString(4, searchValue);
             pst.setString(5, searchValue);
             
             ResultSet rs = pst.executeQuery();
             
             boolean found = false;
             
             while(rs.next()){
                found = true;
                model.addRow(new Object[]{
                    rs.getInt("PatientID"),
                    rs.getString("FullName"),
                    rs.getString("NationalID"),
                    rs.getString("Phone"),
                    rs.getString("MedicalRecordNo")
                });
            }
             if(!found){
                 JOptionPane.showMessageDialog(this, "No patient found");
             }
             rs.close();
             pst.close();
             conn.close();
            }catch(SQLException e){
                JOptionPane.showMessageDialog(this, "Error searching patients: " + e.getMessage());
            }
    }//GEN-LAST:event_btnSearchActionPerformed

