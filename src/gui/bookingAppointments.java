    private void loadDefaultPatients(){
      DefaultTableModel model = (DefaultTableModel)tblPatients.getModel();
      
      model.setRowCount(0);
      
      String sql = "SELECT PatientID, FullName, NationalID, Phone, "
              + "MedicalRecordNo From Patients";
      
      try{
          Connection conn = DBConnection.getConnection();
          PreparedStatement pst = conn.prepareStatement(sql);
          ResultSet rs = pst.executeQuery();
          
          while(rs.next()){
             
              model.addRow(new Object[]{
                  
                  rs.getInt("PatientID"),
                  rs.getString("FullName"),
                  rs.getString("NationalID"),
                  rs.getString("Phone"),
                  rs.getString("MedicalRecordNo")
              });
          }
          rs.close();
          pst.close();
          conn.close();
      }catch(SQLException e){
          JOptionPane.showMessageDialog(this, "Error loading patinets: " + e.getMessage());
      }
    }
