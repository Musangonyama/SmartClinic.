    /**
     * CREATE QR IMAGE FOR PRINTING
     */
    private BufferedImage createQRCodeImage(
            int patientID,
            int width,
            int height) {

        try {

            String qrData =
                    "SMARTCLINIC:PATIENT:" + patientID;

            QRCodeWriter qrCodeWriter =
                    new QRCodeWriter();

            BitMatrix bitMatrix =
                    qrCodeWriter.encode(
                            qrData,
                            BarcodeFormat.QR_CODE,
                            width,
                            height
                    );

            return MatrixToImageWriter.toBufferedImage(
                    bitMatrix
            );

        } catch (WriterException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error creating QR Code: "
                    + e.getMessage()
            );

            return null;
        }
    }
    private boolean loadSelectedPatientDetails() {

    int selectedRow = tblPatients.getSelectedRow();

    if (selectedRow == -1) {

        JOptionPane.showMessageDialog(
                this,
                "Please select a patient first."
        );

        return false;
    }

    registeredPatientID =
            Integer.parseInt(
                    tblPatients.getValueAt(selectedRow, 1).toString()
            );

    registeredPatientName =
            tblPatients.getValueAt(selectedRow, 2).toString();

    String sql = "SELECT FullName, DateOfBirth, MedicalRecordNo "
            + "FROM Patients "
            + "WHERE PatientID = ?";

    try {

        Connection conn = DBConnection.getConnection();
        PreparedStatement pst = conn.prepareStatement(sql);

        pst.setInt(1, registeredPatientID);

        ResultSet rs = pst.executeQuery();

        if (rs.next()) {

            registeredPatientName =
                    rs.getString("FullName");

            registeredPatientDOB =
                    rs.getString("DateOfBirth");

            registeredMedicalRecordNo =
                    rs.getString("MedicalRecordNo");

            rs.close();
            pst.close();
            conn.close();

            return true;
        }

        rs.close();
        pst.close();
        conn.close();

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error loading patient details: "
                + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }

    return false;
}
