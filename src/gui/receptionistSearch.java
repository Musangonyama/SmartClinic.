    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
    String search = txtSearch.getText().trim();

    if (search.isEmpty()) {
        loadPatients();
        return;
    }

    DefaultTableModel model =
            (DefaultTableModel) tblPatients.getModel();

    model.setRowCount(0);

    String sql = "SELECT PatientID, FullName, NationalID, Phone, Status "
            + "FROM Patients "
            + "WHERE Status = 'Active' "
            + "AND ("
            + "CAST(PatientID AS TEXT) LIKE ? "
            + "OR FullName LIKE ? "
            + "OR Phone LIKE ? "
            + "OR NationalID LIKE ?"
            + ") "
            + "ORDER BY FullName";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        String searchValue = "%" + search + "%";

        pst.setString(1, searchValue);
        pst.setString(2, searchValue);
        pst.setString(3, searchValue);
        pst.setString(4, searchValue);

        try (ResultSet rs = pst.executeQuery()) {
            int patientNo = 1;

            while (rs.next()) {
                model.addRow(new Object[]{
                    patientNo++,                 // Display numbering
                    rs.getInt("PatientID"),       // Actual database ID
                    rs.getString("FullName"),
                    rs.getString("NationalID"),
                    rs.getString("Phone"),
                    rs.getString("Status")
                });
            }

            if (patientNo == 1) {
                JOptionPane.showMessageDialog(
                        this,
                        "No active patient found."
                );
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Error searching patient: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }

    }//GEN-LAST:event_btnSearchActionPerformed

