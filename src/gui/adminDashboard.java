private void createChronicFollowUpCases() {

    String sql =
        "SELECT a.AppointmentID, a.PatientID, a.AppointmentDate " +
        "FROM Appointments a " +
        "WHERE a.Department = 'Chronic Care' " +
        "AND UPPER(a.Status) IN ('NO-SHOW', 'NO SHOW') " +
        "AND date(a.AppointmentDate) <= date('now', '-1 month') " +
        "AND NOT EXISTS ( " +
        "    SELECT 1 " +
        "    FROM ChronicFollowUp cf " +
        "    WHERE cf.PatientID = a.PatientID " +
        ")";

    String insertSql =
        "INSERT INTO ChronicFollowUp " +
        "(PatientID, AssignedCHWID, CreatedDate, ExpectedVisitDate, " +
        "LastVisitDate, Status, Escalated) " +
        "VALUES (?, NULL, date('now','localtime'), ?, ?, 'UNASSIGNED', 0)";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {

            int patientID = rs.getInt("PatientID");
            String appointmentDate = rs.getString("AppointmentDate");

            try (PreparedStatement insertPst =
                     con.prepareStatement(insertSql)) {

                insertPst.setInt(1, patientID);
                insertPst.setString(2, appointmentDate);

                // The patient's last recorded visit is not necessarily
                // the missed appointment, so leave this NULL for now.
                insertPst.setNull(3, java.sql.Types.VARCHAR);

               

                insertPst.executeUpdate();
            }
        }

    } catch (SQLException e) {
        e.printStackTrace();
    }
}

private void backupDatabase() {

    JFileChooser fileChooser = new JFileChooser();

    fileChooser.setDialogTitle(
            "Choose Location For Smart Clinic Database Backup"
    );

    String fileName = "SmartClinic_Backup_"
            + new SimpleDateFormat("yyyy-MM-dd_HH-mm-ss")
                    .format(new Date())
            + ".db";

    fileChooser.setSelectedFile(new File(fileName));

    int result = fileChooser.showSaveDialog(this);

    if (result != JFileChooser.APPROVE_OPTION) {
        return;
    }

    File backupFile = fileChooser.getSelectedFile();

    if (!backupFile.getName().toLowerCase().endsWith(".db")) {
        backupFile = new File(
                backupFile.getAbsolutePath() + ".db"
        );
    }

    if (backupFile.exists()) {
        int confirm = JOptionPane.showConfirmDialog(
                this,
                "This backup file already exists. Replace it?",
                "Confirm Overwrite",
                JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        if (!backupFile.delete()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Could not replace the existing backup file.",
                    "Backup Error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }
    }

    try (Connection con = DBConnection.getConnection()) {

        String destination = backupFile.getAbsolutePath()
                .replace("'", "''");

        String sql = "VACUUM INTO '" + destination + "'";

        try (java.sql.Statement stmt = con.createStatement()) {
            stmt.execute(sql);
        }

        if (backupFile.exists() && backupFile.length() > 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "Database backup completed successfully!\n\n"
                    + "Saved to:\n"
                    + backupFile.getAbsolutePath()
                    + "\n\nFile size: "
                    + backupFile.length() + " bytes",
                    "Backup Successful",
                    JOptionPane.INFORMATION_MESSAGE
            );
        } else {
            JOptionPane.showMessageDialog(
                    this,
                    "The backup file was not created correctly.",
                    "Backup Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Database backup failed.\n\n"
                + e.getMessage(),
                "Backup Error",
                JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }
}

   
