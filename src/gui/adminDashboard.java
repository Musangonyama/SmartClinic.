private void loadDepartmentActivity() {

    DefaultTableModel model =
            (DefaultTableModel) tblDepartmentActivity.getModel();

    model.setRowCount(0);

     String sql =
        "SELECT Department, "
        + "SUM(CASE "
        + "WHEN UPPER(TRIM(status)) = 'WAITING' "
        + "THEN 1 ELSE 0 END) AS Waiting, "

        + "SUM(CASE "
        + "WHEN UPPER(TRIM(status)) = 'IN CONSULTATION' "
        + "THEN 1 ELSE 0 END) AS InConsultation, "

        + "SUM(CASE "
        + "WHEN UPPER(TRIM(status)) = 'COMPLETED' "
        + "THEN 1 ELSE 0 END) AS Completed "

        + "FROM Queue "
        + "WHERE QueueDate = date('now','localtime') "
        + "GROUP BY Department "
        + "ORDER BY Department";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {

            String department = rs.getString("Department");
            int waiting = rs.getInt("Waiting");
            int inConsultation = rs.getInt("InConsultation");
            int completed = rs.getInt("Completed");

            model.addRow(new Object[]{
                department,
                waiting,
                inConsultation,
                completed
            });
        }

    } catch (SQLException e) {

        e.printStackTrace();
    }
}
