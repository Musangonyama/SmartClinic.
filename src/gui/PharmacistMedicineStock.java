    private void loadStock() {

    DefaultTableModel model = (DefaultTableModel) tblStock.getModel();
    model.setRowCount(0);

    String sql =
        "SELECT Medicine, Quantity, StockStatus, MarkedLowDate " +
        "FROM MedicineStock " +
        "ORDER BY Medicine ASC";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getString("Medicine"),
                rs.getInt("Quantity"),
                rs.getString("StockStatus"),
                rs.getString("MarkedLowDate")
            });
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Could not load medicine stock.\n\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );
        e.printStackTrace();
    }
}
    private void addMedicine() {

    String medicine = JOptionPane.showInputDialog(
        this,
        "Enter medicine name:",
        "Add Medicine",
        JOptionPane.QUESTION_MESSAGE
    );

    if (medicine == null) {
        return;
    }

    medicine = medicine.trim();

    if (medicine.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter a medicine name.",
            "Invalid Medicine",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String quantityText = JOptionPane.showInputDialog(
        this,
        "Enter current quantity for " + medicine + ":",
        "Initial Quantity",
        JOptionPane.QUESTION_MESSAGE
    );

    if (quantityText == null) {
        return;
    }

    int quantity;

    try {
        quantity = Integer.parseInt(quantityText.trim());

        if (quantity < 0) {
            throw new NumberFormatException();
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "Quantity must be a whole number of 0 or more.",
            "Invalid Quantity",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String sql =
        "INSERT INTO MedicineStock " +
        "(Medicine, Quantity, StockStatus) " +
        "VALUES (?, ?, 'NORMAL')";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, medicine);
        pst.setInt(2, quantity);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(
            this,
            medicine + " has been added to medicine stock.",
            "Medicine Added",
            JOptionPane.INFORMATION_MESSAGE
        );

        loadStock();

    } catch (SQLException e) {

        if (e.getMessage().toLowerCase().contains("unique")) {

            JOptionPane.showMessageDialog(
                this,
                medicine + " already exists in medicine stock.",
                "Medicine Already Exists",
                JOptionPane.WARNING_MESSAGE
            );

        } else {

            JOptionPane.showMessageDialog(
                this,
                "Could not add medicine.\n\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
            );

            e.printStackTrace();
        }
    }
}
 private void updateQuantity() {

    int row = tblStock.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(
            this,
            "Please select a medicine first.",
            "No Medicine Selected",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String medicine = tblStock.getValueAt(row, 0).toString();

    String quantityText = JOptionPane.showInputDialog(
        this,
        "Enter the new quantity for " + medicine + ":",
        "Update Quantity",
        JOptionPane.QUESTION_MESSAGE
    );

    if (quantityText == null) {
        return;
    }

    int quantity;

    try {
        quantity = Integer.parseInt(quantityText.trim());

        if (quantity < 0) {
            throw new NumberFormatException();
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "Quantity must be a whole number of 0 or more.",
            "Invalid Quantity",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String sql =
        "UPDATE MedicineStock " +
        "SET Quantity = ? " +
        "WHERE Medicine = ?";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, quantity);
        pst.setString(2, medicine);

        int updated = pst.executeUpdate();

        if (updated > 0) {

            JOptionPane.showMessageDialog(
                this,
                medicine + " quantity has been updated.",
                "Quantity Updated",
                JOptionPane.INFORMATION_MESSAGE
            );

            loadStock();
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Could not update quantity.\n\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }
}
 private void markLowStock() {

    int row = tblStock.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(
            this,
            "Please select a medicine first.",
            "No Medicine Selected",
            JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String medicine = tblStock.getValueAt(row, 0).toString();

    int confirm = JOptionPane.showConfirmDialog(
        this,
        "Mark " + medicine + " as LOW STOCK?",
        "Low Stock",
        JOptionPane.YES_NO_OPTION,
        JOptionPane.WARNING_MESSAGE
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    String sql =
        "UPDATE MedicineStock " +
        "SET StockStatus = 'LOW STOCK', " +
        "    MarkedLowDate = datetime('now','localtime'), " +
        "    MarkedLowBy = ? " +
        "WHERE Medicine = ?";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, UserSession.staffID);
        pst.setString(2, medicine);

        int updated = pst.executeUpdate();

        if (updated > 0) {

            JOptionPane.showMessageDialog(
                this,
                medicine + " has been marked as LOW STOCK.",
                "Stock Alert",
                JOptionPane.INFORMATION_MESSAGE
            );

            loadStock();
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Could not mark medicine as low stock.\n\n"
            + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }
}
