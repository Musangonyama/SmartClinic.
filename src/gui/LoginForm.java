    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // TODO add your handling code here:
         String username = txtUsername.getText().trim();
    String password = new String(txtlogPass.getPassword());

    // Check empty fields
    if (username.isEmpty() || password.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Please enter username and password.",
                "Login",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    String sql = "SELECT StaffID, FullName, Username, Password, Role, "
           + "Status, Department, Room "
           + "FROM Staff "
           + "WHERE Username = ? "
           + "AND Status = 'Active'";

    try {
        Connection con = DBConnection.getConnection();

        PreparedStatement pst = con.prepareStatement(sql);

       pst.setString(1, username);

ResultSet rs = pst.executeQuery();

if (rs.next()
        && PasswordUtil.verify(
                password,
                rs.getString("Password"))) {

            int staffID = rs.getInt("StaffID");

            String fullName = rs.getString("FullName");
            String role = rs.getString("Role");
            String department = rs.getString("Department");
            String room = rs.getString("Room");

            UserSession.setUser(
                    staffID,
                    staffID,
                    fullName,
                    role,
                    department,
                    room
            );

            System.out.println("LOGIN SUCCESSFUL");
            System.out.println("Staff ID: " + staffID);
            System.out.println("Name: " + fullName);
            System.out.println("Role: " + role);
            System.out.println("Department: " + department);
            System.out.println("Room: " + room);

            JOptionPane.showMessageDialog(
                    this,
                    "Login successful!",
                    "Login",
                    JOptionPane.INFORMATION_MESSAGE
            );

        

           if (role.equalsIgnoreCase("Admin")) {

    adminDashboard admin = new adminDashboard();
    admin.setVisible(true);
    this.dispose();

} else if (role.equalsIgnoreCase("Nurse")) {

    NurseDashboard nurse = new NurseDashboard();
    nurse.setVisible(true);
    this.dispose();

}else if(role.equalsIgnoreCase("Doctor")) {
    DoctorDashboard dd = new DoctorDashboard();
    dd.setVisible(true);
    this.dispose();
}else if(role.equalsIgnoreCase("Pharmacist")){
    PharmacistDashboard pd = new PharmacistDashboard();
    pd.setVisible(true);
    this.dispose();
}else if(role.equalsIgnoreCase("Receptionist")){
    receptionistDashboard rd = new receptionistDashboard();
    rd.setVisible(true);
    this.dispose();
}else if(role.equalsIgnoreCase("CHW")){
    CHWDashboard chw = new CHWDashboard();
    chw.setVisible(true);
    this.dispose();
}else{

    JOptionPane.showMessageDialog(
            this,
            "Welcome, " + fullName
            + "\nRole: " + role
            + "\nDepartment: " + department
            + "\nRoom: " + room,
            "Login Successful",
            JOptionPane.INFORMATION_MESSAGE
    );
}

        } else {

           

            JOptionPane.showMessageDialog(
                    this,
                    "Invalid username or password,\n"
                    + "or the staff account is inactive.",
                    "Login Failed",
                    JOptionPane.ERROR_MESSAGE
            );
        }

        rs.close();
        pst.close();

    } catch (Exception e) {

        JOptionPane.showMessageDialog(this, "Login error: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);

        e.printStackTrace();
    }
    }//GEN-LAST:event_btnLoginActionPerformed

