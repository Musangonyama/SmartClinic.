private void startQueueAutoRefresh() {
    // Refresh the queue every 30 seconds.
    queueRefreshTimer = new javax.swing.Timer(30000, e -> loadQueue());
    queueRefreshTimer.start();
}



private void loadQueue() {
    DefaultTableModel model =
            (DefaultTableModel) tblQueue.getModel();

    model.setRowCount(0);

    String selectedDepartment =
            cmbDepartment.getSelectedItem().toString();

    String sql =
            "SELECT q.queueNumber, "
            + "p.FullName AS PatientName, "
            + "q.Department, "
            + "q.checkInTime, "
            + "CASE "
            + "WHEN q.appointmentID IS NULL THEN 'Walk-In' "
            + "ELSE 'Appointment' "
            + "END AS VisitType, "
            + "q.status "
            + "FROM Queue q "
            + "JOIN Patients p "
            + "ON q.patientID = p.PatientID "
            + "WHERE date(q.QueueDate) = date('now', 'localtime') "
            + "AND UPPER(TRIM(q.status)) IN "
            + "('WAITING', 'IN CONSULTATION') ";

    if (!selectedDepartment.equals("All Departments")) {
        sql += "AND q.Department = ? ";
    }

    sql += "ORDER BY q.checkInTime ASC";

    try (Connection conn = DBConnection.getConnection();
         PreparedStatement pst = conn.prepareStatement(sql)) {

        if (!selectedDepartment.equals("All Departments")) {
            pst.setString(1, selectedDepartment);
        }

        try (ResultSet rs = pst.executeQuery()) {
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("queueNumber"),
                    rs.getString("PatientName"),
                    rs.getString("Department"),
                    rs.getString("checkInTime"),
                    rs.getString("VisitType"),
                    rs.getString("status")
                });
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Error loading queue: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

